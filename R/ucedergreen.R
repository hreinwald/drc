#' Effective dose for the U-shaped Cedergreen-Ritz-Streibig model
#'
#' @description
#' Internal helper returning the ED and its gradient for \code{\link{ucedergreen}}. The U-shaped
#' curve starts at \code{c}, dips, and then increases towards \code{d} (\code{b > 0}). The dose
#' is searched on the increasing branch beyond the dip, where the equation has a unique root.
#'
#' @param parm numeric vector of the non-fixed parameters.
#' @param all_params numeric vector template with all parameters (b, c, d, e, f).
#' @param not_fixed logical vector flagging the non-fixed parameters.
#' @param alpha the fixed shape parameter.
#' @param respl response level: percent of the way from \code{c} to \code{d} for
#'   \code{type = "relative"}, the response itself for \code{type = "absolute"}.
#' @param reference \code{"control"} (percentage measured from \code{c}) or otherwise
#'   percentage measured down from \code{d}.
#' @param type \code{"relative"} or \code{"absolute"}.
#' @param lower,upper dose search interval.
#'
#' @return list(ED, gradient of ED w.r.t. the non-fixed parameters); \code{NA}s with a warning if
#'   the level is not reached.
#'
#' @keywords internal
ucedergreen_edfct <- function(parm, all_params, not_fixed, alpha, respl, reference, type,
                              lower = 1e-4, upper = 10000)
{
  fail <- function(msg) {
    warning(msg, call. = FALSE)
    list(NA_real_, rep(NA_real_, sum(not_fixed)))
  }

  th <- all_params
  th[not_fixed] <- parm
  if (th[1] <= 0) return(fail("ED for the U-shaped CRS model requires b > 0. Returning NA."))
  if (th[3] == th[2]) return(fail("Upper and lower asymptotes are equal. Returning NA."))

  ufun <- function(x, th) {
    th[3] - (th[3] - th[2] + th[5] * exp(-1 / x^alpha)) / (1 + exp(th[1] * (log(x) - log(th[4]))))
  }

  # percentage of the way from c to d (percent measured from c) and the target response
  if (identical(type, "absolute")) {
    pct <- 100 * (respl - th[2]) / (th[3] - th[2])
  } else if (identical(reference, "control")) {
    pct <- respl
  } else {
    pct <- 100 - respl
  }
  target <- th[2] + pct / 100 * (th[3] - th[2])

  # dose with minimal response: the increasing branch starts here
  grid <- exp(seq(log(lower), log(upper), length.out = 1000))
  xDip <- grid[which.min(ufun(grid, th))]

  g <- function(lx) ufun(exp(lx), th) - target
  gLo <- g(log(xDip))
  gHi <- g(log(upper))
  if (!is.finite(gLo) || !is.finite(gHi) || gLo > 0 || gHi < 0) {
    return(fail(paste0("Response level ", respl, " is not reached on the increasing branch of the curve. Returning NA.")))
  }
  edVal <- exp(uniroot(g, c(log(xDip), log(upper)), tol = 1e-12)$root)

  # Gradient by the implicit function theorem: dED/dtheta = -(du/dtheta - dtarget/dtheta) / du/dx
  hx <- edVal * 1e-6
  dudx <- (ufun(edVal + hx, th) - ufun(edVal - hx, th)) / (2 * hx)
  dudth <- vapply(seq_along(th), function(k) {
    h <- max(abs(th[k]), 1) * 1e-6
    thUp <- replace(th, k, th[k] + h)
    thDn <- replace(th, k, th[k] - h)
    (ufun(edVal, thUp) - ufun(edVal, thDn)) / (2 * h)
  }, numeric(1))
  dtargdth <- rep(0, 5)
  if (!identical(type, "absolute")) {
    dtargdth[2] <- 1 - pct / 100
    dtargdth[3] <- pct / 100
  }
  grad <- -(dudth - dtargdth) / dudx

  list(edVal, grad[not_fixed])
}

#' @title U-shaped Cedergreen-Ritz-Streibig model
#'
#' @description
#' \code{ucedergreen} provides a very general way of specifying the Cedergreen-Ritz-Streibig
#' modified log-logistic model for describing u-shaped hormesis, under various constraints on the parameters.
#'
#' @param fixed A numeric vector of length 5 specifying any parameters to be held fixed
#'   during the estimation. The order is \code{c(b, c, d, e, f)}. Use \code{NA} for
#'   parameters that should be estimated. The default is to estimate all parameters.
#' @param names A character vector of length 5 providing names for the parameters.
#'   The default is \code{c("b", "c", "d", "e", "f")}.
#' @param method A character string specifying the method for the self-starter function
#'   to use for finding initial parameter values. Options are \code{"loglinear"},
#'   \code{"anke"}, \code{"method3"}, and \code{"normolle"}. This is only used if \code{ssfct} is \code{NULL}.
#' @param ssfct A custom self-starter function. If \code{NULL} (the default), a
#'   self-starter is automatically generated by calling \code{\link{cedergreen.ssf}}
#'   with the specified \code{method}, \code{fixed}, and \code{alpha} arguments.
#' @param alpha A mandatory numeric value specifying the fixed shape parameter \eqn{\alpha}.
#'   The function will stop if this is not provided.
#' @param fctName An optional character string to name the function object.
#' @param fctText An optional character string providing a descriptive text for the model.
#'
#' @details
#' The u-shaped model is the mirror image of the decreasing Cedergreen-Ritz-Streibig (CRS)
#' model of Cedergreen et al. (2005), reflected about the mid-level \eqn{(c+d)/2}:
#' \deqn{f(x) = d - \frac{d-c+f \exp(-1/x^{\alpha})}{1+\exp(b(\log(x)-\log(e)))}}
#' equivalently \eqn{f(x) = c + d - \mathrm{CRS}(x)}. Hence \eqn{f(0) = c} and
#' \eqn{f(x) \to d} for \eqn{x \to \infty} (for \eqn{b > 0}), i.e. \code{c} is the response of the
#' untreated control and \code{d} the upper limit. The U-shaped model is an extension in this package;
#' Cedergreen et al. (2005) define only the decreasing model.
#'
#' The parameters are: \code{b}, the slope; \code{c}, the lower and \code{d} the upper asymptote;
#' \code{e}, the location of the transition; and \code{f}, the size of the hormetic
#' deviation at low doses (the response dips below \code{c}). As for the CRS model, \code{b} and \code{e}
#' lose their usual slope and ED50 interpretation when \eqn{f \ne 0}. Effective doses
#' (\code{\link{ED}}) are the doses at which the response has covered \code{p} percent of the way from
#' \code{c} to \code{d} on the increasing branch beyond the dip; for \code{type = "absolute"} the
#' response level itself is supplied. The wrappers \code{\link{UCRS.4a}}-\code{\link{UCRS.5c}} fix \eqn{\alpha} at
#' 1, 0.5 and 0.25 (suffix a, b, c) and, for the four-parameter versions, \code{c} at 0.
#'
#' @return A list of class \code{"UCRS"}, containing the model function (\code{fct}),
#'   the self-starter function (\code{ssfct}), parameter names (\code{names}), and other
#'   components required for use with modeling functions like \code{\link[drc]{drm}}.
#'
#' @references
#' Cedergreen, N. and Ritz, C. and Streibig, J. C. (2005)
#' Improved empirical models describing hormesis,
#' \emph{Environmental Toxicology and Chemistry} \bold{24}, 3166--3172.
#'
#' @author Christian Ritz, Hannes Reinwald
#'
#' @seealso \code{\link{cedergreen}}, \code{\link{UCRS.4a}}, \code{\link{UCRS.5a}}, \code{\link{drm}}
#'
#' @examples
#' ## Simulated U-shaped data: fit with drm() and plot
#' dose <- rep(c(0.1, 0.3, 1, 3, 10, 30, 100, 300), each = 3)
#' mu <- ucedergreen(alpha = 1)$fct(dose, matrix(c(1.5, 1, 6, 10, -2), length(dose), 5, byrow = TRUE))
#' dat <- data.frame(dose = dose, response = mu + 0.15 * sin(seq_along(dose) * 2.3))
#' m1 <- drm(response ~ dose, data = dat, fct = ucedergreen(alpha = 1))
#' plot(m1, type = "all", main = "U-shaped Cedergreen-Ritz-Streibig model")
#'
#' ## Effect of the asymptotes: fix c (lower) at 0 or d (upper) at 4
#' m.c0 <- drm(response ~ dose, data = dat, fct = ucedergreen(alpha = 1, fixed = c(NA, 0, NA, NA, NA)))
#' m.d4 <- drm(response ~ dose, data = dat, fct = ucedergreen(alpha = 1, fixed = c(NA, NA, 4, NA, NA)))
#' plot(m1, type = "all", main = "Fixed asymptotes")
#' plot(m.c0, type = "none", add = TRUE, col = "darkgreen")
#' plot(m.d4, type = "none", add = TRUE, col = "red")
#' legend("topleft", c("free", "c = 0", "d = 4"), col = c("black", "darkgreen", "red"),
#'   lty = 1, bty = "n")
#'
#' @keywords models nonlinear
"ucedergreen" <- function(
    fixed  = c(NA, NA, NA, NA, NA),
    names  = c("b", "c", "d", "e", "f"),
    method = c("loglinear", "anke", "method3", "normolle"),
    ssfct  = NULL,
    alpha,
    fctName,
    fctText
){
    ## Checking arguments and setting up fixed parameter logic
    numParm <- 5
    if (!is.character(names) || !(length(names) == numParm)) {stop("Not correct 'names' argument")}
    if (!(length(fixed) == numParm)) {stop("Not correct 'fixed' argument")}
    if (missing(alpha)) {stop("'alpha' argument must be specified")}

    # Determine if fixed parameters are being used. This will be passed to ssfct.
    useFixed <- !all(is.na(fixed))

    # Match the method argument
    method   <- match.arg(method)
    notFixed <- is.na(fixed)
    parmVec  <- rep(0, numParm)
    parmVec[!notFixed] <- fixed[!notFixed]

    ## Defining the non-linear function
    fct <- function(dose, parm)
    {
        parmMat <- matrix(parmVec, nrow(parm), numParm, byrow = TRUE)
        parmMat[, notFixed] <- parm

        numTerm <- parmMat[, 3] - parmMat[, 2] + parmMat[, 5]*exp(-1/dose^alpha)
        denTerm <- 1 + exp(parmMat[, 1]*(log(dose) - log(parmMat[, 4])))
        # U-shaped model: mirror image of the CRS model, f(x) = d - numTerm/denTerm = c + d - CRS(x)
        parmMat[, 3] - numTerm/denTerm
    }

    ## --- Correctly defining the self-starter ---
    # If a custom self-starter is not provided, use our robust cedergreen.ssf
    if (is.null(ssfct)) {
        # Delegate to the external self-starter, passing method, fixed, alpha, and useFixed.
        ssfct_inner <- cedergreen.ssf(method = method, fixed = fixed, alpha = alpha, useFixed = useFixed)
        ssfct <- function(dframe) {
            initval <- ssfct_inner(dframe)
            # For U-shaped model, negate the b parameter if it's not fixed
            if (is.na(fixed[1])) {
                initval[1] <- -initval[1]
            }
            return(initval)
        }
    }

    ## Defining names for the parameters to be estimated
    names <- names[notFixed]

    ## Specifying the derivatives
    deriv1 <- function(dose, parm)
    {
        parmMat <- matrix(parmVec, nrow(parm), numParm, byrow=TRUE)
        parmMat[, notFixed] <- parm

        t0 <- exp(-1/(dose^alpha))
        t1 <- parmMat[, 3] - parmMat[, 2] + parmMat[, 5]*t0
        t2 <- exp(parmMat[, 1]*(log(dose) - log(parmMat[, 4])))
        t3 <- 1 + t2
        t4 <- (1 + t2)^(-2)

        cbind( t1*xlogx(dose/parmMat[, 4], parmMat[, 1])*t4,
               1/t3,
               1 - 1/t3,
               -t1*t2*(parmMat[, 1]/parmMat[, 4])*t4,
               -t0/t3 )[, notFixed]
    }

    deriv2 <- NULL

    ## Defining the ED function: dedicated closure (the CRS root finder works on the decreasing branch)
    edfct <- function(parm, respl, reference, type, lower = 1e-4, upper = 10000, ...)
    {
        ucedergreen_edfct(parm, parmVec, notFixed, alpha, respl, reference, type, lower, upper)
    }

    ## Finding the maximal hormesis: wrapper closure that delegates to cedergreen_maxfct
    ## The framework calls maxfct(parm, lower, upper) where parm is the non-fixed
    ## parameter vector. We reconstruct the full named-list and bind alpha.
    maxfct <- function(parm, lower = 1e-3, upper = 1000, .optimize_fn = stats::optimize)
    {
        parmVec[notFixed] <- parm
        all_params <- list(b = parmVec[1], c = parmVec[2], d = parmVec[3],
                           e = parmVec[4], f = parmVec[5])
        retVal <- cedergreen_maxfct(all_params, alpha, lower, upper, .optimize_fn)
        # For U-shaped: invert the response
        retVal[2] <- (parmVec[2] + parmVec[3]) - retVal[2]
        return(retVal)
    }

    # Return results
    returnList <- list(
        fct    = fct,
        ssfct  = ssfct,
        names  = names,
        deriv1 = deriv1,
        deriv2 = NULL,
        edfct  = edfct,
        maxfct = maxfct,
        name   = ifelse(missing(fctName), as.character(match.call()[[1]]), fctName),
        text   = ifelse(missing(fctText), "U-shaped Cedergreen-Ritz-Streibig", fctText),
        noParm = sum(is.na(fixed))
    )

    class(returnList) <- "UCRS"
    invisible(returnList)
}


#' @title U-shaped CRS model with lower limit 0 (alpha=1)
#'
#' @description
#' Four-parameter u-shaped CRS hormesis model with lower limit fixed at 0 and alpha=1.
#'
#' @param names a vector of character strings giving the names of the parameters.
#' @param ... additional arguments passed to \code{\link{ucedergreen}}.
#'
#' @return A list (see \code{\link{ucedergreen}}).
#'
#' @seealso \code{\link{ucedergreen}}, \code{\link{UCRS.5a}}, \code{\link{CRS.4a}}
#'
#' @examples
#' ## Simulated U-shaped data (c = 0, alpha = 1): fit with drm() and plot
#' dose <- rep(c(0.1, 0.3, 1, 3, 10, 30, 100, 300), each = 3)
#' mu <- ucedergreen(alpha = 1, fixed = c(NA, 0, NA, NA, NA))$fct(dose,
#'   matrix(c(1.5, 6, 10, -2), length(dose), 4, byrow = TRUE))
#' dat <- data.frame(dose = dose, response = mu + 0.15 * sin(seq_along(dose) * 2.3))
#' m1 <- drm(response ~ dose, data = dat, fct = UCRS.4a())
#' plot(m1, type = "all", main = "UCRS.4a")
#'
#' @keywords models nonlinear
"UCRS.4a" <-
function(names = c("b", "d", "e", "f"), ...)
{
    ## Checking arguments
    if (!is.character(names) || !(length(names) == 4)) {stop("Not correct 'names' argument")}

    return(ucedergreen(names = c(names[1], "c", names[2:4]), fixed = c(NA, 0, NA, NA, NA), alpha = 1, ...))
}

